BEGIN;

-- MDATE user accounts. Passwords are always stored as bcrypt hashes, never plaintext.
-- This init schema supports fresh databases. Existing volumes use migration 004_local_identity.sql.
CREATE TABLE users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email TEXT NULL,
    email_verified BOOLEAN NOT NULL DEFAULT FALSE,
    password_hash TEXT NULL,
    display_name TEXT NULL,
    preferred_language TEXT NOT NULL DEFAULT 'en-MY',
    status TEXT NOT NULL DEFAULT 'PENDING_SETUP'
        CHECK (status IN ('PENDING_SETUP', 'ACTIVE', 'SUSPENDED', 'DELETED')),
    setup_completed_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ NULL,
    CHECK (email IS NULL OR length(trim(email)) > 0),
    CHECK (display_name IS NULL OR length(trim(display_name)) > 0),
    CHECK (
        (status = 'DELETED' AND deleted_at IS NOT NULL)
        OR (status <> 'DELETED' AND deleted_at IS NULL)
    )
);

CREATE UNIQUE INDEX users_email_lower_uq
    ON users (lower(email)) WHERE email IS NOT NULL AND deleted_at IS NULL;

CREATE TABLE roles (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    description TEXT NULL
);

CREATE TABLE user_roles (
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role_id SMALLINT NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
    granted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    granted_by UUID NULL REFERENCES users(id) ON DELETE SET NULL,
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE accessibility_preferences (
    user_id UUID PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    text_size TEXT NOT NULL DEFAULT 'medium'
        CHECK (text_size IN ('small', 'medium', 'large')),
    contrast TEXT NOT NULL DEFAULT 'normal'
        CHECK (contrast IN ('normal', 'high')),
    alternative_input_on BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE voice_preferences (
    user_id UUID PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    preferred_voice_id TEXT NULL,
    audio_rate NUMERIC(3,2) NOT NULL DEFAULT 1.00
        CHECK (audio_rate BETWEEN 0.50 AND 2.00),
    audio_volume NUMERIC(3,2) NOT NULL DEFAULT 1.00
        CHECK (audio_volume BETWEEN 0.00 AND 1.00),
    voice_disabled BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMIT;
